def get_layout(mode):
    if mode == "abc":
        return [
            ["+", "1", "2", "3", "4", "5", "*", "6", "7", "8", "9", "0", "⌫"],
            ["Q", "W", "E", "R", "T", "Y", "U", "I", "O", "P"],
            ["A", "S", "D", "F", "G", "H", "J", "K", "L", "Ñ"],
            ["⚡ SHIFT", "Z", "X", "C", "V", "B", "N", "M", ",", ".", "?123"],
            ["ESPACIO", "ENTER"]
        ]
    else:
        return [
            ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0", "⌫"],
            ["+", "-", "*", "/", "%", "$", "@", "&", "(", ")"],
            ["!", "?", "\"", "'", ":", ";", ",", ".", "=", "\\"],
            ["ABC", "ESPACIO", "ENTER"]
        ]
